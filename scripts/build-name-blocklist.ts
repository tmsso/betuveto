/**
 * Compile data/name-blocklist/{hu,en}.txt into lib/name-blocklist.generated.ts (see
 * lib/name-filter.ts for the match modes). Re-run after updating either source list:
 *
 *   npx tsx scripts/build-name-blocklist.ts
 *
 * An entry of 5+ letters gets `prefix` mode unless it begins a different word in our own
 * wordlists (data/magyar-szavak.txt, data/english-words.txt) — then it falls back to
 * `exact`, so "franc" can't block "Francia". FORCE_PREFIX overrides that for entries whose
 * only colliding dictionary words are themselves vulgar compounds.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { lettersOnly, normalizeForBlocklist } from "../lib/name-filter.js";

const MIN_PREFIX_LENGTH = 5;
// Collisions checked by hand (2026-10-15): kurvaéletbe, csöcsök, seggfejű, szajhaság,
// bastardise — all offensive themselves.
const FORCE_PREFIX = new Set(["kurva", "csöcs", "seggfej", "szajha", "bastard"]);

const read = (path: string) => readFileSync(new URL(`../${path}`, import.meta.url), "utf8").split("\n");
const norm = (s: string) => lettersOnly(normalizeForBlocklist(s.trim()));

const entries = [...new Set(["data/name-blocklist/hu.txt", "data/name-blocklist/en.txt"].flatMap(read).map(norm))]
  .filter(Boolean)
  .sort();
const dictionary = ["data/magyar-szavak.txt", "data/english-words.txt"].flatMap(read).map(norm).filter(Boolean);

const exact: string[] = [];
const prefix: string[] = [];
for (const entry of entries) {
  const collides = dictionary.some((word) => word !== entry && word.startsWith(entry));
  if (entry.length >= MIN_PREFIX_LENGTH && (!collides || FORCE_PREFIX.has(entry))) prefix.push(entry);
  else exact.push(entry);
}

const out = `// GENERATED by scripts/build-name-blocklist.ts from data/name-blocklist/ (LDNOOBW,
// CC BY 4.0 — see data/README.md). Do not edit by hand; edit the generator and re-run.
export const NAME_BLOCKLIST: { exact: string[]; prefix: string[] } = ${JSON.stringify({ exact, prefix }, null, 0)};
`;
writeFileSync(new URL("../lib/name-blocklist.generated.ts", import.meta.url), out);
console.log(`exact ${exact.length}, prefix ${prefix.length}`);
